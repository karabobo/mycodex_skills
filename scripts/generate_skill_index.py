#!/usr/bin/env python3
"""generate_skill_index.py — write SKILL-INDEX.md for the DSH rendering.

The index is generated from the canonical tree plus the rendered tree, so it
stays in sync automatically. It is a navigation aid: phase grouping mirrors
the bigpowers pattern, where each skill declares a ``phase`` in frontmatter.

Usage:
    python3 scripts/generate_skill_index.py            # write SKILL-INDEX.md
    python3 scripts/generate_skill_index.py --stdout   # print instead of write
"""

from __future__ import annotations

import argparse
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
sys.path.insert(0, os.path.join(SCRIPT_DIR, "lib"))

from lib.skill_ir import (  # noqa: E402
    CATALOG_DESCRIPTION_MAX_LENGTH,
    iterate_skills,
    normalize_description,
    parse_skill,
)

# Phase order used for grouping; a skill without a ``phase`` lands in "General".
PHASE_ORDER = [
    "Discover",
    "Design",
    "Plan",
    "Build",
    "Verify",
    "Release",
    "Sustain",
    "General",
]


def collect() -> list[dict]:
    records = []
    for path in iterate_skills(os.path.join(REPO_ROOT, "skills")):
        record = parse_skill(path)
        raw, _ = _split_frontmatter_text(path)
        phase = _field(raw, "phase") or "General"
        records.append(
            {
                "name": record.name,
                "description": record.description,
                "phase": phase,
                "source": os.path.relpath(path, REPO_ROOT),
            }
        )
    return records


def _split_frontmatter_text(path: str) -> tuple[str, str]:
    with open(path, "r", encoding="utf-8") as handle:
        text = handle.read()
    match = re.match(r"\A---\r?\n(.*?)\r?\n---", text, re.S)
    return (match.group(1), text) if match else ("", text)


def _field(raw: str, key: str) -> str:
    match = re.search(r"^%s\s*:\s*(.*)$" % re.escape(key), raw, re.M)
    if not match:
        return ""
    value = match.group(1).strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def render_index(records: list[dict]) -> str:
    lines = [
        "# SKILL-INDEX.md",
        "",
        "Auto-generated by `scripts/generate_skill_index.py`. DO NOT EDIT.",
        "",
        f"{len(records)} skills. Each skill is rendered for DeepSeek Harness by",
        "`scripts/sync-skills.sh`; the canonical source lives in `skills/`.",
        "",
    ]

    phases = {}
    for record in records:
        phases.setdefault(record["phase"], []).append(record)

    ordered = [p for p in PHASE_ORDER if p in phases] + sorted(
        p for p in phases if p not in PHASE_ORDER
    )

    lines.append("## Quick nav")
    lines.append("")
    lines.append("| Phase | Skills |")
    lines.append("| --- | --- |")
    for phase in ordered:
        lines.append(f"| {phase} | {len(phases[phase])} |")
    lines.append("")

    lines.append("## Reference")
    lines.append("")
    lines.append("| Phase | Skill | Description | Status |")
    lines.append("| --- | --- | --- | --- |")
    for phase in ordered:
        for record in sorted(phases[phase], key=lambda r: r["name"]):
            description = normalize_description(record["description"])
            if len(description) > CATALOG_DESCRIPTION_MAX_LENGTH:
                description = description[: CATALOG_DESCRIPTION_MAX_LENGTH - 3] + "..."
            lines.append(
                f"| {phase} | `{record['name']}` | {description} | active |"
            )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate SKILL-INDEX.md.")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args()

    records = collect()
    content = render_index(records)

    if args.stdout:
        print(content)
        return 0

    target = os.path.join(REPO_ROOT, "SKILL-INDEX.md")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(f"generate_skill_index: wrote {target} ({len(records)} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
